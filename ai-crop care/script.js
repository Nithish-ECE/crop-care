function addChatMessage(message, type) {
  const container = document.getElementById('chatMessages');
  const bubble = document.createElement('div');
  bubble.className = `chat-bubble ${type}`;
  bubble.textContent = message;
  container.appendChild(bubble);
}

function chatAnswer(question) {
  const q = question.toLowerCase();
  if (q.includes('fertilizer') || q.includes('urea') || q.includes('nutrient') || q.includes('npk')) return t('chatFertilizer');
  if (q.includes('disease') || q.includes('yellow') || q.includes('leaf') || q.includes('blight') || q.includes('fungus') || q.includes('spot')) return t('chatDisease');
  if (q.includes('price') || q.includes('market') || q.includes('rate') || q.includes('cost')) return t('chatPrice');
  if (q.includes('scheme') || q.includes('subsidy') || q.includes('pm-kisan') || q.includes('soil health')) return t('chatScheme');
  if (q.includes('weather') || q.includes('rain') || q.includes('temperature')) return t('chatWeather');
  if (q.includes('irrigation') || q.includes('water') || q.includes('drip')) return t('chatIrrigation');
  if (q.includes('soil') || q.includes('ph')) return t('chatSoil');
  return t('chatFallback');
}

function sendChatMessage() {
  const input = document.getElementById('chatInput');
  const question = input.value.trim();
  if (!question) return;
  addChatMessage(question, 'user');
  addChatMessage(chatAnswer(question), 'bot');
  input.value = '';
}

